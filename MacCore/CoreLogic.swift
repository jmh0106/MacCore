enum AICompletionClassifier {
    static func normalizedProvider(_ value: String) -> String? {
        let value = value.lowercased()
        if value.contains("antigravity") { return "Antigravity" }
        if value.contains("claude code") || value.contains("claude-code") { return "Claude Code" }
        if value.contains("codex") { return "Codex" }
        return nil
    }

    static func provider(appName: String, bundleID: String?, title: String, detail: String) -> String? {
        let source = "\(appName) \(bundleID ?? "") \(title) \(detail)".lowercased()
        guard let provider = normalizedProvider(source) else { return nil }

        let message = "\(title) \(detail)".lowercased()
        let completionPhrases = ["task completed", "task complete", "turn completed", "turn complete",
                                 "agent completed", "work completed", "finished the task",
                                 "작업 완료", "작업을 완료", "작업이 끝났", "완료했습니다", "완료했어요"]
        return completionPhrases.contains(where: message.contains) ? provider : nil
    }
}

enum ContinuousTime {
    private static let scale: Double = {
        var info = mach_timebase_info_data_t()
        mach_timebase_info(&info)
        return Double(info.numer) / Double(info.denom) / 1_000_000_000
    }()
    static var now: TimeInterval { Double(mach_continuous_time()) * scale }
}

struct Countdown {
    private(set) var duration: TimeInterval = 25 * 60
    private(set) var paused: TimeInterval = 25 * 60
    private(set) var deadline: TimeInterval?
    var isRunning: Bool { deadline != nil }

    func remaining(at now: TimeInterval) -> TimeInterval {
        max(0, deadline.map { $0 - now } ?? paused)
    }

    mutating func start(seconds: TimeInterval, at now: TimeInterval) {
        guard seconds.isFinite, seconds > 0 else { return }
        duration = seconds
        paused = seconds
        deadline = now + seconds
    }

    mutating func pause(at now: TimeInterval) {
        paused = remaining(at: now)
        deadline = nil
    }

    mutating func resume(at now: TimeInterval) {
        guard !isRunning, paused > 0 else { return }
        deadline = now + paused
    }

    mutating func reset() { deadline = nil; paused = duration }

    mutating func restore(duration: TimeInterval, remaining: TimeInterval, running: Bool, at now: TimeInterval) {
        guard duration.isFinite, duration > 0, duration <= 24 * 3600, remaining.isFinite else { return }
        self.duration = duration
        paused = min(duration, max(0, remaining))
        deadline = running && paused > 0 ? now + paused : nil
    }

    mutating func finishIfNeeded(at now: TimeInterval) -> Bool {
        guard isRunning, remaining(at: now) <= 0 else { return false }
        deadline = nil
        paused = 0
        return true
    }

    static func display(_ seconds: TimeInterval) -> String {
        let bounded = seconds.isFinite ? min(Double(Int32.max), max(0, seconds)) : 0
        let value = Int(ceil(bounded))
        if value >= 3600 {
            return String(format: "%d:%02d:%02d", value / 3600, value / 60 % 60, value % 60)
        }
        return String(format: "%02d:%02d", value / 60, value % 60)
    }
}

enum PomodoroCycle {
    static func focusDuration(minutes: Int) -> TimeInterval {
        TimeInterval(min(180, max(1, minutes)) * 60)
    }

    static func next(isOnBreak: Bool, completedSessions: Int, sessionCount: Int) -> (isOnBreak: Bool, completedSessions: Int, finished: Bool) {
        let completed = completedSessions + (isOnBreak ? 0 : 1)
        return (!isOnBreak, completed, completed >= max(1, sessionCount))
    }
}

enum ClipboardPolicy {
    static func mayRecord(source: String?, excludedApps: String, types: [String]) -> Bool {
        let excluded = Set(excludedApps.split(whereSeparator: \.isNewline).map { $0.trimmingCharacters(in: .whitespaces) })
        let sensitive: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]
        return !excluded.contains(source ?? "") && sensitive.isDisjoint(with: types)
    }
}

enum NowPlayingTiming {
    static func position(elapsed: Double?, timestamp: Double?, rate: Double?, playing: Bool,
                         duration: Double, at now: TimeInterval = Date().timeIntervalSince1970) -> Double {
        let snapshot = elapsed.flatMap { $0.isFinite ? max(0, $0) : nil } ?? 0
        let speed = rate.flatMap { $0.isFinite ? min(16, max(0, $0)) : nil } ?? 1
        let delta = timestamp.flatMap { $0.isFinite && now.isFinite ? max(0, now - $0) : nil } ?? 0
        let estimate = snapshot + (playing ? delta * speed : 0)
        let position = estimate.isFinite ? estimate : snapshot
        return duration.isFinite && duration > 0 ? min(duration, position) : position
    }
}

struct FileDragActivation {
    private var idleChangeCount: Int
    private(set) var active = false

    init(changeCount: Int) { idleChangeCount = changeCount }

    mutating func update(changeCount: Int, mouseDown: Bool, hasFiles: Bool, nearIsland: Bool) -> Bool {
        guard mouseDown else {
            idleChangeCount = changeCount
            active = false
            return false
        }
        guard !active, changeCount != idleChangeCount, hasFiles, nearIsland else { return false }
        active = true
        return true
    }

    mutating func dismiss(changeCount: Int) {
        if active { idleChangeCount = changeCount }
        active = false
    }
}

enum OverlayLayout {
    static func fileDragActivationFrame(screen: CGRect, compactWidth: CGFloat) -> CGRect {
        let width = min(screen.width, max(360, compactWidth + 120))
        return CGRect(x: screen.midX - width / 2, y: screen.maxY - 180, width: width, height: 180)
    }

    static func compactSize(menuBarHeight: CGFloat, music: Bool, timer: Bool, noticeWidth: CGFloat?, hovered: Bool) -> CGSize {
        guard music || timer || noticeWidth != nil else { return CGSize(width: 44, height: menuBarHeight) }
        if noticeWidth != nil && (music || timer) {
            return CGSize(width: music ? 272 : 240, height: max(30, menuBarHeight) * 2 + 1 + (hovered ? 6 : 0))
        }
        let width = noticeWidth ?? (timer ? 152 : 272)
        return CGSize(width: width + (hovered ? 18 : 0), height: max(30, menuBarHeight) + (hovered ? 6 : 0))
    }

    static func surfaceFrame(canvasWidth: CGFloat, size: CGSize, topInset: CGFloat) -> CGRect {
        CGRect(x: (canvasWidth - size.width) / 2, y: topInset, width: size.width, height: size.height)
    }

    static func menuBarHeight(screen: CGRect, visible: CGRect) -> CGFloat {
        min(64, max(24, screen.maxY - visible.maxY))
    }

    static func frame(in screen: CGRect, visible: CGRect, size: CGSize) -> CGRect {
        let width = min(size.width, visible.width - 16)
        let height = min(size.height, screen.maxY - visible.minY - 8)
        let centeredX = screen.midX - width / 2
        let originX = min(max(centeredX, visible.minX + 8), visible.maxX - width - 8)
        return CGRect(x: originX, y: screen.maxY - height, width: width, height: height)
    }

    static func menuPanelFrame(anchor: CGRect, visible: CGRect, size: CGSize) -> CGRect {
        let width = min(size.width, visible.width - 16)
        let top = min(anchor.minY - 6, visible.maxY - 6)
        let height = min(size.height, max(1, top - visible.minY - 8))
        let x = min(max(anchor.midX - width / 2, visible.minX + 8), visible.maxX - width - 8)
        return CGRect(x: x, y: max(visible.minY + 8, top - height), width: width, height: height)
    }
}

struct CPUSample {
    let user: UInt32
    let system: UInt32
    let idle: UInt32
    let nice: UInt32

    func utilization(since previous: CPUSample) -> Double? {
        let busy = Double(user &- previous.user) + Double(system &- previous.system) + Double(nice &- previous.nice)
        let total = busy + Double(idle &- previous.idle)
        return total > 0 ? min(1, max(0, busy / total)) : nil
    }
}

struct NetworkSample {
    let received: UInt64
    let sent: UInt64
    let time: TimeInterval
    let interfaces: Set<String>

    func rates(since previous: NetworkSample) -> (down: Double, up: Double)? {
        let elapsed = time - previous.time
        guard elapsed > 0, interfaces == previous.interfaces,
              received >= previous.received, sent >= previous.sent else { return nil }
        return (Double(received - previous.received) / elapsed, Double(sent - previous.sent) / elapsed)
    }
}

func byteString(_ bytes: Int64) -> String {
    ByteCountFormatter.string(fromByteCount: max(0, bytes), countStyle: .memory)
}

func speedString(_ bytes: Double?) -> String {
    guard let bytes else { return "측정 중" }
    if bytes < 1024 { return String(format: "%.0f B/s", bytes) }
    if bytes < 1024 * 1024 { return String(format: "%.1f KB/s", bytes / 1024) }
    return String(format: "%.1f MB/s", bytes / 1024 / 1024)
}
